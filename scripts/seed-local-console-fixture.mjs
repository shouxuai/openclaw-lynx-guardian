#!/usr/bin/env node

import { existsSync, readFileSync } from "fs";
import os from "os";
import path from "path";

const baseUrl = "http://127.0.0.1:31789";
const tokenPath = path.join(os.homedir(), ".openclaw", "lynx", "data", "console.token");
const token = process.env.LYNX_LOCAL_CONSOLE_TOKEN
  ?? (existsSync(tokenPath) ? readFileSync(tokenPath, "utf8").trim() : "");

if (!token) {
  console.error(`[seed-local-console-fixture] missing ingest token; expected env LYNX_LOCAL_CONSOLE_TOKEN or ${tokenPath}`);
  process.exit(1);
}

